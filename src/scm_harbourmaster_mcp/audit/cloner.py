@dataclass
class SnippetPlan:
    """What the clone does with one of the customer's source snippets."""

    source: str
    target: str
    # "create": new snippet in the target; "reuse": the target already has it
    # and no other folder uses it; "shared": it exists and other folders use
    # it, so its objects are written only with allow_shared_snippet; "pan":
    # the name is one of PAN's snippets, which is never written to.
    action: str
    objects: int = 0
    source_folders: list[str] = field(default_factory=list)
    target_folders: list[str] = field(default_factory=list)
    description: str = ""
    enable_prefix: bool = False
    dropped_labels: list[str] = field(default_factory=list)
    write_objects: bool = True
    failed: str = ""
    # Filled when the clone runs: "created", "associated", "already associated", or an error
    outcome: list[str] = field(default_factory=list)


_SNIPPET_ACTIONS = {
    "create": "new snippet",
    "reuse": "exists, no other folder uses it",
    "shared": "exists and other folders use it",
    "pan": "PAN snippet, never written to",
}


def _snippet_markdown(plans: list[SnippetPlan], target_folder: str) -> list[str]:
    lines = [
        "\n## Snippets\n",
        f"Objects from the customer's own snippets go into a snippet of the same name, "
        f"associated with `{target_folder}`.\n",
        "| Source snippet | Target snippet | Objects | Target state | Source folders | Outcome |",
        "|---|---|---|---|---|---|",
    ]
    for p in plans:
        state = _SNIPPET_ACTIONS.get(p.action, p.action)
        if p.action == "shared":
            state += f" ({', '.join(f'`{f}`' for f in p.target_folders)})"
        outcome = "; ".join(p.outcome) or "—"
        lines.append(
            f"| `{p.source}` | `{p.target}` | {p.objects} | {state} | "
            f"{', '.join(f'`{f}`' for f in p.source_folders) or '—'} | {outcome} |"
        )
    for p in plans:
        if p.action == "shared" and not p.write_objects:
            lines.append(
                f"\n⚠️ `{p.target}` is already used by "
                f"{', '.join(f'`{f}`' for f in p.target_folders)}: its objects were not written, "
                "and the existing snippet is associated as it is. Pass "
                "allow_shared_snippet=True to write into it, which changes those folders too."
            )
        elif p.action == "shared":
            lines.append(
                f"\n⚠️ Writing into `{p.target}` also changes "
                f"{', '.join(f'`{f}`' for f in p.target_folders)}."
            )
        if p.dropped_labels:
            lines.append(
                f"\n- `{p.target}`: labels not copied ({', '.join(p.dropped_labels)}); "
                "labels must exist in the target tenant."
            )
    return lines


def _setup_rows(session: Any, kind: str) -> list[dict[str, Any]]:
    resp = session.get(f"{_SETUP_V1}/{kind}", params={"limit": "1000"}, timeout=60)
    if not resp.ok:
        raise RuntimeError(f"{kind}: HTTP {resp.status_code}: {resp.text[:200]}")
    body = resp.json() if resp.content else {}
    rows = body.get("data", []) if isinstance(body, dict) else body
    return [r for r in rows or [] if isinstance(r, dict)]


def _plan_snippets(
    session: Any,
    data: dict[str, Any],
    objects_by_snippet: dict[str, int],
    target_folder: str,
    name_prefix: str,
    allow_shared_snippet: bool,
) -> list[SnippetPlan]:
    """One SnippetPlan per customer snippet whose objects this clone pushes."""
    recorded = {
        str(s.get("name")): s
        for s in data.get("snippets") or []
        if isinstance(s, dict) and s.get("name")
    }
    types = {str(s.get("name")): s.get("type") for s in _setup_rows(session, "snippets")}
    used_by: dict[str, list[str]] = {}
    for f in _setup_rows(session, "folders"):
        for sn in f.get("snippets") or []:
            used_by.setdefault(str(sn), []).append(str(f.get("name")))
    folder = _API_FOLDER_ALIASES.get(target_folder, target_folder)

    plans: list[SnippetPlan] = []
    for source in sorted(objects_by_snippet):
        rec = recorded.get(source, {})
        target = f"{name_prefix}{source}"
        others = sorted(set(used_by.get(target, [])) - {folder})
        if target not in types:
            action = "create"
        elif types[target] in PAN_SNIPPET_TYPES or target.startswith("predefined"):
            # PAN's own snippet: never written to (backups without snippet_types)
            action = "pan"
        elif others:
            action = "shared"
        else:
            action = "reuse"
        plans.append(
            SnippetPlan(
                source=source,
                target=target,
                action=action,
                objects=objects_by_snippet[source],
                source_folders=list(rec.get("folders") or []),
                target_folders=sorted(used_by.get(target, [])),
                description=str(rec.get("description") or ""),
                enable_prefix=bool(rec.get("enable_prefix")),
                # Labels must already exist in the target tenant; never sent
                dropped_labels=list(rec.get("labels") or []),
                write_objects=action in ("create", "reuse")
                or (action == "shared" and allow_shared_snippet),
            )
        )
    return plans


def _snippet_capable(sdk_attr: str, folder: str, opts: dict[str, Any]) -> bool:
    """Objects of this batch can live in a snippet: not the fixed Prisma
    Access folders, the Mobile-Users folder-kwarg APIs or folderless ones."""
    return (
        folder == "customer"
        and not opts.get("folder_kwarg")
        and sdk_attr not in _FOLDERLESS_RESOURCES
    )


def _apply_snippet_plans(
    session: Any, plans: list[SnippetPlan], target_folder: str, dry_run: bool
) -> list[str]:
    """Create the missing snippets, then associate them with the folder.

    Returns warnings for the report.
    """
    for p in plans:
        if p.action == "pan":
            p.outcome.append("not written")
            continue
        if p.action == "create":
            if dry_run:
                p.outcome.append("would create")
                continue
            try:
                _create_snippet(session, p)
                p.outcome.append("created")
            except Exception as exc:
                p.failed = str(exc)[:200]
                p.outcome.append(f"create failed: {p.failed}")
    warnings = [
        f"Snippet `{p.target}` could not be created ({p.failed}); its objects were not pushed."
        for p in plans
        if p.failed
    ]
    names = [p.target for p in plans if p.action != "pan" and not p.failed]
    if not names:
        return warnings
    if dry_run:
        for p in plans:
            if p.target in names:
                p.outcome.append(f"would associate with `{target_folder}`")
        return warnings
    try:
        added = _associate_snippets(session, target_folder, names)
    except Exception as exc:
        for p in plans:
            if p.target in names:
                p.outcome.append(f"association failed: {str(exc)[:200]}")
        warnings.append(
            f"Snippets {', '.join(f'`{n}`' for n in names)} could not be associated with "
            f"`{target_folder}` ({str(exc)[:200]}): their objects are in the snippets but the "
            "folder does not see them. Associate them in the SCM UI before pushing."
        )
        return warnings
    for p in plans:
        if p.target in names:
            p.outcome.append(
                f"associated with `{target_folder}`" if p.target in added else "already associated"
            )
    return warnings


def _rule_order_warnings(
    resources: dict[str, Any],
    batches: list[tuple[str, str, str, dict[str, Any]]],
    plans: list[SnippetPlan],
    target_folder: str,
    snippet_names: set[str],
) -> list[str]:
    """One warning per preserved snippet that receives rules.

    A snippet's rules are evaluated where its row sits in the folder's
    rulebase.  The source position is the source folder's placeholder row.
    """
    by_source = {p.source: p for p in plans if p.write_objects and not p.failed}
    warnings: list[str] = []
    for source, plan in sorted(by_source.items()):
        keys = [
            b[0]
            for b in batches
            if b[0] in _RULE_KEYS
            and any(
                isinstance(o, dict) and o.get("snippet") == source
                for o in resources.get(b[0]) or []
            )
        ]
        if not keys:
            continue
        where: list[str] = []
        for key in keys:
            rows = [o for o in resources.get(key) or [] if isinstance(o, dict)]
            folder_rows = [o for o in rows if not o.get("snippet")]
            for i, o in enumerate(folder_rows):
                if o.get("name") == source and _is_snippet_row(key, o, snippet_names):
                    where.append(f"{key}: row {i + 1} of {len(folder_rows)}")
        src = f" (source: {'; '.join(where)})" if where else ""
        # Live 2026-10-13: a newly associated snippet's row lands after the
        # inherited snippet rows and above every rule of the folder's own.
        warnings.append(
            f"Rules in snippet `{plan.target}` ({', '.join(keys)}) are evaluated where the "
            f"snippet sits in `{target_folder}`'s rulebase. SCM adds a newly associated snippet "
            f"above the folder's own rules, so they run before them{src}. Check the rule order "
            "in the SCM UI before pushing."
        )
    return warnings


def _create_snippet(session: Any, plan: SnippetPlan) -> None:
    body: dict[str, Any] = {"name": plan.target}
    if plan.description:
        body["description"] = plan.description
    if plan.enable_prefix:
        body["enable_prefix"] = True
    resp = session.post(f"{_SETUP_V1}/snippets", json=body, timeout=60)
    if not resp.ok:
        raise RuntimeError(f"HTTP {resp.status_code}: {resp.text[:200]}")


def _associate_snippets(session: Any, target_folder: str, names: list[str]) -> list[str]:
    """Add *names* to the folder's snippet list; returns the names added."""
    folder = _API_FOLDER_ALIASES.get(target_folder, target_folder)
    row = next((f for f in _setup_rows(session, "folders") if f.get("name") == folder), None)
    if row is None or not row.get("id"):
        raise RuntimeError(f"target folder `{target_folder}` not found")
    resp = session.get(f"{_SETUP_V1}/folders/{row['id']}", timeout=60)
    if not resp.ok:
        raise RuntimeError(f"HTTP {resp.status_code}: {resp.text[:200]}")
    current = resp.json()
    have = [str(s) for s in current.get("snippets") or []]
    added = [n for n in names if n not in have]
    if not added:
        return []
    # The PUT takes the whole folder; anything left out would be cleared
    body = {k: v for k, v in current.items() if k != "id"}
    body["snippets"] = have + added
    put = session.put(f"{_SETUP_V1}/folders/{row['id']}", json=body, timeout=60)
    if not put.ok:
        raise RuntimeError(f"HTTP {put.status_code}: {put.text[:200]}")
    return added


def _drop_nulls(value: Any) -> Any:
    """Drop null fields, recursively.

    SCM response models serialise every unset field as null, but the create
    models reject null where they expect a value or their own default — an
    app-override rule read back with "application": null cannot be replayed.
    """
    if isinstance(value, dict):
        return {k: _drop_nulls(v) for k, v in value.items() if v is not None}
    if isinstance(value, list):
        return [_drop_nulls(v) for v in value]
    return value


# Threat profiles whose rules SCM reads back with action {} when the rule uses
# the signature's default action.  Create rejects both {} and {"default": {}}
# ("missing node 'action'"); omitting the key round-trips back to {}.
_THREAT_RULE_PROFILES = frozenset({"anti_spyware_profiles", "vulnerability_profiles"})


def _drop_empty_actions(obj: dict[str, Any]) -> None:
    for rule in obj.get("rules") or []:
        if isinstance(rule, dict) and rule.get("action") == {}:
            del rule["action"]


def _anonymise_ips(obj: dict[str, Any], ip_map: dict[str, str]) -> dict[str, Any]:
    """Replace IPv4 addresses in a dict (recursively) with template vars."""
    text = json.dumps(obj)

    def _replace(m: re.Match[str]) -> str:
        ip = m.group(1)
        suffix = m.group(2)
        if ip not in ip_map:
            n = len(ip_map) + 1
            ip_map[ip] = f"{{{{IP_{n}}}}}"
        return str(ip_map[ip]) + str(suffix)

    return dict(json.loads(_IP_RE.sub(_replace, text)))


def _scrub_psk(obj: dict[str, Any], gateway_name: str) -> tuple[dict[str, Any], bool]:
    """Replace PSK in an IKE gateway dict. Returns (modified_obj, was_scrubbed)."""
    obj = copy.deepcopy(obj)
    scrubbed = False
    try:
        auth = obj.get("authentication", {})
        if "pre_shared_key" in auth:
            auth["pre_shared_key"]["key"] = f"CHANGEME_{gateway_name}"
            scrubbed = True
        elif isinstance(auth.get("pre_shared_key"), str):
            auth["pre_shared_key"] = f"CHANGEME_{gateway_name}"
            scrubbed = True
    except Exception:
        pass
    return obj, scrubbed


def _apply_name_prefix(obj: dict[str, Any], prefix: str) -> dict[str, Any]:
    if prefix and "name" in obj:
        obj = dict(obj)
        obj["name"] = f"{prefix}{obj['name']}"
    return obj


def _sanitise(
    obj: dict[str, Any],
    *,
    target_folder: str,
    name_prefix: str,
    anonymise_ips: bool,
    ip_map: dict[str, str],
    is_ike_gateway: bool = False,
    set_folder: bool = True,
    rewrite: Callable[[dict[str, Any]], Any] | None = None,
    snippet: str = "",
) -> tuple[dict[str, Any], str | None]:
    """
    Returns (sanitised_obj, psk_warning_or_None).

    *snippet* puts the object in that snippet instead of *target_folder*.
    *rewrite* points references at renamed objects.  It runs before IP
    anonymisation, which would otherwise change an IP-bearing name such as
    ``H-192.0.2.1`` before the rename map could match it.
    """
    o = _drop_nulls(_strip_system_fields(copy.deepcopy(obj)))
    # SCM models accept exactly one container, so the source snippet/device has
    # to go before the target folder is set.
    o.pop("snippet", None)
    o.pop("device", None)
    # Resources whose folder travels as a create() kwarg (GP Mobile-Users API)
    # must not carry a folder key in the payload at all.
    if snippet:
        o.pop("folder", None)
        o["snippet"] = snippet
    elif set_folder:
        o["folder"] = target_folder
    else:
        o.pop("folder", None)

    psk_warning: str | None = None
    if is_ike_gateway:
        name = obj.get("name", "unknown")
        o, scrubbed = _scrub_psk(o, name)
        if scrubbed:
            psk_warning = f"{name_prefix}{name}" if name_prefix else name

    if name_prefix:
        o = _apply_name_prefix(o, name_prefix)
    if rewrite is not None:
        rewrite(o)

    if anonymise_ips:
        o = _anonymise_ips(o, ip_map)

    return o, psk_warning


def _to_update_model(resource: Any, payload: dict[str, Any]) -> Any:
    """Wrap *payload* in whatever update model this resource's update() takes.

    Every SDK resource types its update() first argument as its own
    ``*UpdateModel``; passing a bare dict raises inside the SDK.
    """
    try:
        # eval_str resolves the annotation when the defining module uses
        # postponed evaluation, where it would otherwise arrive as a string.
        sig = inspect.signature(resource.update, eval_str=True)
    except Exception:
        sig = inspect.signature(resource.update)
    params = [p for n, p in sig.parameters.items() if n != "self"]
    annotation = params[0].annotation if params else None
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation(**payload)
    return payload


class _RestResource:
    """Minimal create/fetch/update adapter for config resources pan-scm-sdk
    does not wrap, so ``_push_one`` can treat them like SDK resources."""

    def __init__(self, session: Any, url: str) -> None:
        self._session = session
        self._url = url

    @staticmethod
    def _check(resp: Any) -> Any:
        if not resp.ok:
            # Body carries the SCM error text ("Object already exists", ...)
            # that the conflict detection in _push_one matches on.
            raise RuntimeError(f"HTTP {resp.status_code}: {resp.text[:300]}")
        return resp.json() if resp.content else {}

    def create(self, data: dict[str, Any]) -> Any:
        return self._check(self._session.post(self._url, json=data, timeout=30))

    def fetch(self, name: str, folder: str = "", snippet: str = "") -> Any:
        container = {"snippet": snippet} if snippet else {"folder": folder}
        body = self._check(
            self._session.get(self._url, params={"name": name, **container}, timeout=30)
        )
        items = body.get("data", [body]) if isinstance(body, dict) else body
        if not items:
            raise RuntimeError(f"{name!r} not found in {container}")
        return type("Existing", (), {"id": items[0].get("id")})()

    def update(self, data: dict[str, Any]) -> Any:
        # The container is fixed at create time; PUT bodies carry neither it nor the id
        payload = {k: v for k, v in data.items() if k not in ("id", "folder", "snippet", "device")}
        return self._check(self._session.put(f"{self._url}/{data['id']}", json=payload, timeout=30))


# Resources pushed via raw REST: profile groups have no pan-scm-sdk wrapper
# (0.15.1), and its application-filter model has no "tagging" field, which
# the API returns and filters on.
_REST_ONLY_RESOURCES: dict[str, str] = {
    "profile_group": "https://api.sase.paloaltonetworks.com/sse/config/v1/profile-groups",
    "application_filter": "https://api.sase.paloaltonetworks.com/config/objects/v1/application-filters",
    # NGFW network config (include_network)
    **{
        _network_attr(key): f"{_NETWORK_V1}/{path}"
        for key, path in NETWORK_CONFIG_RESOURCES.items()
    },
}


# Resources the API never reports as a name conflict: a duplicate create is
# accepted under a generated name (e.g. GP auth settings → "UserAuth_<ts>").
_RENAMES_ON_DUPLICATE = frozenset({"auth_setting"})


def _exists(
    resource: Any, name: str, payload: dict[str, Any], create_kwargs: dict[str, str]
) -> bool:
    folder = create_kwargs.get("folder") or payload.get("folder") or _FOLDER_MOBILE_USERS
    try:
        resource.fetch(name=name, folder=folder)
    except Exception:
        return False
    return True


def _rest_create_fallback(
    client: Any, resource: Any, exc: Exception, create_kwargs: dict[str, str]
) -> _RestResource | None:
    """REST adapter for a create the SDK rejected client-side.

    The SDK create models are stricter than SCM — e.g. their name pattern
    forbids spaces, which SCM accepts — so a local validation error is retried
    as a raw POST.  Only folder-in-payload creates qualify: rulebase and folder
    kwargs travel as query parameters the adapter does not send.
    """
    if "validation error" not in str(exc).lower() or create_kwargs:
        return None
    endpoint = getattr(resource, "ENDPOINT", None)
    session = getattr(client, "session", None)
    base = getattr(client, "api_base_url", None)
    if not (endpoint and session is not None and base):
        return None
    logger.info("clone_sdk_validation_rest_fallback", endpoint=endpoint)
    return _RestResource(session, f"{base}{endpoint}")


# pan-scm-sdk (0.15.1) create()/update() serialise these without by_alias, so
# aliased fields never reach SCM and are dropped without an error: a URL
# profile's "continue" action, a HIP object's "is" criteria, vulnerability
# rules' "vendor-id".  They are pushed over REST with the keys renamed instead.
_ALIASED_KEYS: dict[str, dict[str, str]] = {
    "url_access_profile": {"continue_": "continue"},
    "hip_object": {"is_": "is"},
    "vulnerability_protection_profile": {"vendor_id": "vendor-id"},
}


def _rename_keys(value: Any, renames: dict[str, str]) -> Any:
    if isinstance(value, dict):
        return {renames.get(k, k): _rename_keys(v, renames) for k, v in value.items()}
    if isinstance(value, list):
        return [_rename_keys(v, renames) for v in value]
    return value


class _AliasedRestResource(_RestResource):
    """REST adapter that sends the API's field names for SDK-aliased keys."""

    def __init__(self, session: Any, url: str, renames: dict[str, str]) -> None:
        super().__init__(session, url)
        self._renames = renames

    def create(self, data: dict[str, Any]) -> Any:
        return super().create(_rename_keys(data, self._renames))

    def update(self, data: dict[str, Any]) -> Any:
        return super().update(_rename_keys(data, self._renames))


def _resource(client: Any, sdk_attr: str) -> Any:
    if sdk_attr in _REST_ONLY_RESOURCES:
        return _RestResource(client.session, _REST_ONLY_RESOURCES[sdk_attr])
    resource = getattr(client, sdk_attr)
    renames = _ALIASED_KEYS.get(sdk_attr)
    endpoint = getattr(resource, "ENDPOINT", None)
    base = getattr(client, "api_base_url", None)
    if renames and endpoint and base:
        return _AliasedRestResource(client.session, f"{base}{endpoint}", renames)
    return resource


def _push_one(
    client: Any,
    sdk_attr: str,
    payload: dict[str, Any],
    on_conflict: str,
    dry_run: bool,
    resource_type: str,
    create_kwargs: dict[str, str] | None = None,
) -> PushResult:
    name = payload.get("name", "<unknown>")
    create_kwargs = create_kwargs or {}
    if dry_run:
        if payload.get("snippet"):
            detail = f"would create in snippet '{payload['snippet']}'"
        else:
            shown_folder = str(create_kwargs.get("folder") or payload.get("folder", ""))
            detail = f"would create in folder '{shown_folder}'"
        if create_kwargs:
            detail += " (" + ", ".join(f"{k}={v}" for k, v in create_kwargs.items()) + ")"
        return PushResult(resource_type, name, "dry_run", detail)
    try:
        resource = _resource(client, sdk_attr)
        if sdk_attr in _RENAMES_ON_DUPLICATE and _exists(resource, name, payload, create_kwargs):
            if on_conflict == "skip":
                return PushResult(resource_type, name, "skipped", "already exists")
            return PushResult(
                resource_type, name, "failed", "exists; overwrite unsupported for this type"
            )
        try:
            resource.create(payload, **create_kwargs)
        except Exception as exc:
            rest = _rest_create_fallback(client, resource, exc, create_kwargs)
            if rest is None:
                raise
            rest.create(payload)
        logger.info("clone_object_created", type=resource_type, name=name)
        return PushResult(resource_type, name, "created")
    except Exception as exc:
        err = str(exc)
        is_conflict = any(
            x in type(exc).__name__ for x in ("Conflict", "NameNotUnique", "ObjectNotUnique")
        )
        if not is_conflict:
            is_conflict = any(
                p in err.lower() for p in ("already exists", "name not unique", "conflict")
            )
        if is_conflict and on_conflict == "skip":
            return PushResult(resource_type, name, "skipped", "already exists")
        if is_conflict and on_conflict == "overwrite":
            try:
                resource = _resource(client, sdk_attr)
                # Forward the create kwargs (e.g. rulebase=) but keep the
                # folder single-sourced: it may ride in create_kwargs for
                # folder-kwarg resources instead of the payload.
                fetch_kwargs: dict[str, str] = {"name": name}
                if "folder" in create_kwargs:
                    fetch_kwargs["folder"] = str(create_kwargs["folder"])
                elif payload.get("snippet"):
                    fetch_kwargs["snippet"] = str(payload["snippet"])
                else:
                    fetch_kwargs["folder"] = payload.get("folder", "")
                for k, v in create_kwargs.items():
                    if k != "folder":
                        fetch_kwargs[k] = str(v)
                existing = resource.fetch(**fetch_kwargs)
                payload_with_id = dict(payload)
                if hasattr(existing, "id"):
                    payload_with_id["id"] = str(existing.id)
                resource.update(_to_update_model(resource, payload_with_id), **create_kwargs)
                return PushResult(resource_type, name, "overwritten")
            except Exception as upd_exc:
                return PushResult(resource_type, name, "failed", str(upd_exc)[:120])
        logger.warning("clone_object_failed", type=resource_type, name=name, error=err)
        return PushResult(resource_type, name, "failed", err[:120])


def _planned_batches(
    resources: dict[str, Any],
    *,
    include_deployment: bool,
    skip_rules: bool,
    resource_filter: set[str] | None,
    include_network: bool = False,
) -> list[tuple[str, str, str, dict[str, Any]]]:
    """(backup key, sdk attr, folder, _process_batch options) in push order.

    Network config keys are planned only with *include_network* or when
    *resource_filter* names them.
    """

    def network(keys: tuple[str, ...]) -> list[tuple[str, str, str, dict[str, Any]]]:
        return [
            (key, _network_attr(key), "customer", {"network": True})
            for key in keys
            if include_network or (resource_filter and key in resource_filter)
        ]

    batches: list[tuple[str, str, str, dict[str, Any]]] = []
    for snap_key, sdk_attr, folder in _PUSH_ORDER:
        if snap_key == "zones":
            # Zones list interfaces
            batches += network(_NETWORK_INTERFACE_ORDER)
        batches.append((snap_key, sdk_attr, folder, {}))
    batches += network(_NETWORK_ROUTING_ORDER)
    for snap_key, sdk_attr, folder in _FOLDER_KWARG_ORDER:
        batches.append((snap_key, sdk_attr, folder, {"folder_kwarg": True}))
    if not skip_rules:
        rule_order = list(_RULE_ORDER)
        if not resources.get("nat_rules_pre") and not resources.get("nat_rules_post"):
            rule_order.append(_LEGACY_NAT_ORDER)
        for snap_key, sdk_attr, rule_kwargs in rule_order:
            batches.append((snap_key, sdk_attr, "customer", {"create_kwargs": rule_kwargs}))
        batches += network(_NETWORK_RULE_ORDER)
    if include_deployment:
        for snap_key, sdk_attr, folder in _DEPLOY_ORDER:
            batches.append(
                (snap_key, sdk_attr, folder, {"is_ike_gateway": sdk_attr == "ike_gateway"})
            )
    return [
        b
        for b in batches
        if resources.get(b[0]) and not (resource_filter and b[0] not in resource_filter)
    ]


def _run_preflight(
    client: Any,
    resources: dict[str, Any],
    planned_keys: list[str],
    target_folder: str,
    *,
    name_prefix: str,
    on_missing_reference: str,
    on_missing_trust_cert: str,
    inventory: TargetInventory | None,
    snippet_types: dict[str, str],
) -> PreflightResult:
    if on_missing_reference not in MISSING_REFERENCE_MODES:
        raise ValueError(
            f"on_missing_reference must be one of {', '.join(MISSING_REFERENCE_MODES)}"
        )
    if on_missing_trust_cert not in MISSING_TRUST_CERT_MODES:
        raise ValueError(
            f"on_missing_trust_cert must be one of {', '.join(MISSING_TRUST_CERT_MODES)}"
        )
    session = None
    if inventory is None or "decryption_rules" in planned_keys:
        from .extractor import _bearer_session_for

        session = _bearer_session_for(client)
    if inventory is None:
        inventory = fetch_target_inventory(
            session, target_folder, network=bool(NETWORK_KEYS & set(planned_keys))
        )

    def trust_state() -> str:
        from ..tools.tenant_copy import _forward_trust_state

        try:
            return _forward_trust_state(session)
        except Exception as exc:
            logger.warning("clone_preflight_trust_state_failed", error=str(exc)[:200])
            return "unknown"

    return check_references(
        resources,
        planned_keys,
        inventory,
        name_prefix=name_prefix,
        on_missing_reference=on_missing_reference,
        trust_state=trust_state if session is not None else None,
        on_missing_trust_cert=on_missing_trust_cert,
        snippet_types=snippet_types,
    )


def clone_config(
    client: Any,
    source_backup_file: str,
    target_folder: str,
    *,
    name_prefix: str = "",
    anonymise_ips: bool = False,
    include_deployment: bool = False,
    skip_rules: bool = False,
    on_conflict: str = "skip",
    dry_run: bool = True,
    resource_filter: set[str] | None = None,
    on_missing_reference: str | None = None,
    on_missing_trust_cert: str = "fail",
    inventory: TargetInventory | None = None,
    include_network: bool = False,
    snippet_mode: str = "flatten",
    allow_shared_snippet: bool = False,
) -> CloneReport:
    """
    Load *source_backup_file*, sanitise every object, and push to
    *target_folder* on *client*.

    Parameters
    ----------
    client          : Authenticated Scm client.
    source_backup_file : Path to JSON produced by scm_config_backup.
    target_folder   : Destination SCM folder name.
    name_prefix     : Optional prefix applied to every object name.
    anonymise_ips   : Replace IPv4 literals with {{IP_N}} template vars.
    include_deployment : Also clone IKE gateways, IPSec tunnels, RNs, SCs,
                         bandwidth allocations and QoS/DNS infrastructure.
    skip_rules      : Omit all policy rules.
    on_conflict     : 'skip' (default) or 'overwrite'.
    dry_run         : If True, no API writes are made (default: True).
    resource_filter : If set, only process resource types in this set.
    on_missing_reference : Run the reference preflight (clone_preflight.py)
                         against the target before any write: 'fail',
                         'skip_object' or 'strip_member'.  None skips it.
    on_missing_trust_cert : Enabled decrypt rules when the target has no
                         forward-trust certificate: 'fail', 'disable_rule'
                         or 'skip_object'.  Only used with the preflight.
    inventory       : Pre-fetched target inventory (tests); read live if None.
    include_network : Also restore the NGFW network config (NETWORK_KEYS):
                         interface management profiles, interfaces, route
                         lists, BGP/OSPF profiles, logical/virtual routers,
                         GRE tunnels and PBF rules.  Off by default because
                         interfaces are hardware-specific; naming a network
                         key in resource_filter also plans it.  Rows set on a
                         single firewall (device, no folder) are reported, not
                         pushed.  Interface names never take name_prefix.
    snippet_mode    : 'flatten' (default) clones objects from the customer's
                         own snippets into *target_folder*.  'preserve' puts
                         them in a snippet of the same name (plus
                         name_prefix), creating it when the target lacks it,
                         and associates it with *target_folder*.  Objects in
                         fixed folders (Mobile Users, Remote Networks, Service
                         Connections) stay there.  PAN snippets are never
                         written to.
    allow_shared_snippet : With 'preserve', also write into a target snippet
                         that other folders already use (which changes them
                         too).  Otherwise that snippet is only associated.

    GlobalProtect and identity coverage: auth settings, tunnel profiles,
    agent profiles, forwarding profiles, portal/gateway infrastructure
    settings (fixed 'Mobile Users' folder) and SAML/Radius/LDAP auth
    profiles (customer folder) are cloned from the backup when present.
    """
    if snippet_mode not in SNIPPET_MODES:
        raise ValueError(f"snippet_mode must be one of {', '.join(SNIPPET_MODES)}")
    data = json.loads(Path(source_backup_file).read_text())
    resources: dict[str, list[dict[str, Any]]] = data.get("resources", {})

    report = CloneReport(
        source_file=source_backup_file,
        target_folder=target_folder,
        target_tenant_id="",
        dry_run=dry_run,
    )
    ip_map: dict[str, str] = {}
    snippet_types = _snippet_types(data, client)
    if snippet_types is None:
        report.warnings.append(_SNIPPET_TYPES_UNKNOWN)
        snippet_types = {}
    snippet_names = _snippet_names(data, client, snippet_types)
    batches = _planned_batches(
        resources,
        include_deployment=include_deployment,
        skip_rules=skip_rules,
        resource_filter=resource_filter,
        include_network=include_network,
    )

    preflight: PreflightResult | None = None
    if on_missing_reference is not None:
        preflight = _run_preflight(
            client,
            resources,
            [b[0] for b in batches],
            target_folder,
            name_prefix=name_prefix,
            on_missing_reference=on_missing_reference,
            on_missing_trust_cert=on_missing_trust_cert,
            inventory=inventory,
            snippet_types=snippet_types,
        )
        report.preflight = preflight
        if preflight.blocked and not dry_run:
            return report

    # References to objects this clone creates under a prefix follow the rename
    renames: dict[str, dict[str, str]] = {}
    if name_prefix:
        planned = {b[0] for b in batches}
        for key, kinds in PROVIDES.items():
            # Interfaces keep their hardware/variable names
            if key not in planned or key in UNRENAMED_KEYS:
                continue
            for obj in resources.get(key) or []:
                name = str(obj.get("name") or "") if isinstance(obj, dict) else ""
                if not name or pan_snippet(obj, snippet_types) or device_row(obj):
                    continue
                if preflight is not None and (key, name) in preflight.skip:
                    continue
                for kind in kinds:
                    renames.setdefault(kind, {})[name] = f"{name_prefix}{name}"

    # Customer snippets kept as snippets (snippet_mode="preserve")
    snippet_plans: dict[str, SnippetPlan] = {}
    if snippet_mode == "preserve":
        in_snippets: dict[str, int] = {}
        for snap_key, sdk_attr, folder, opts in batches:
            if not _snippet_capable(sdk_attr, folder, opts):
                continue
            for obj in resources.get(snap_key) or []:
                if (
                    isinstance(obj, dict)
                    and obj.get("snippet")
                    and not pan_snippet(obj, snippet_types)
                    and not device_row(obj)
                ):
                    sn = str(obj["snippet"])
                    in_snippets[sn] = in_snippets.get(sn, 0) + 1
        if in_snippets:
            session = client.session
            try:
                plans = _plan_snippets(
                    session, data, in_snippets, target_folder, name_prefix, allow_shared_snippet
                )
            except Exception as exc:
                report.warnings.append(
                    "snippet_mode=preserve: the target's snippets and folders could not be "
                    f"read ({str(exc)[:200]}), so nothing was pushed."
                )
                return report
            report.snippets = plans
            snippet_plans = {p.source: p for p in plans}
            report.warnings += _apply_snippet_plans(session, plans, target_folder, dry_run)
            report.warnings += _rule_order_warnings(
                resources, batches, plans, target_folder, snippet_names
            )

    # Network backup keys holding a name already seen from another folder
    duplicates: list[str] = []

    def _process_batch(
        snap_key: str,
        sdk_attr: str,
        folder: str,
        *,
        is_ike_gateway: bool = False,
        create_kwargs: dict[str, str] | None = None,
        folder_kwarg: bool = False,
        network: bool = False,
        into_snippet: bool = False,
    ) -> None:
        # Network rows of one name from several source folders (an "All"
        # backup walks every firewall folder): name → first source folder
        first_folder: dict[str, str] = {}
        for obj in resources.get(snap_key, []):
            # Checked before sanitising, which drops the source snippet.
            snippet = pan_snippet(obj, snippet_types)
            if snippet:
                detail = (
                    "PAN predefined content — already present in every tenant"
                    if _is_predefined(obj)
                    else f"from PAN snippet `{snippet}` — associate the snippet with the target folder"
                )
                report.results.append(
                    PushResult(snap_key, obj.get("name", "<unknown>"), "predefined", detail)
                )
                continue
            if network and device_row(obj):
                report.results.append(
                    PushResult(
                        snap_key,
                        obj.get("name", "<unknown>"),
                        "device_row",
                        f"set on firewall `{device_row(obj)}` — device-scoped, never pushed "
                        "into a folder",
                    )
                )
                continue
            if _is_snippet_row(snap_key, obj, snippet_names):
                report.results.append(
                    PushResult(
                        snap_key,
                        obj.get("name", "<unknown>"),
                        "not_cloned",
                        "snippet placeholder: stands for a snippet associated with the source "
                        "folder, not a rule",
                    )
                )
                continue
            if network:
                name = str(obj.get("name", ""))
                src = str(obj.get("folder") or "")
                if name in first_folder:
                    duplicates.append(snap_key)
                    report.results.append(
                        PushResult(
                            snap_key,
                            name,
                            "not_cloned",
                            f"same name as the copy from folder `{first_folder[name]}`; "
                            f"this one is from `{src}`",
                        )
                    )
                    continue
                first_folder[name] = src
            oid = (snap_key, str(obj.get("name", "")))
            notes: list[str] = []
            plan = snippet_plans.get(str(obj.get("snippet") or "")) if into_snippet else None
            if plan is not None and (plan.failed or not plan.write_objects):
                report.results.append(
                    PushResult(
                        snap_key,
                        obj.get("name", "<unknown>"),
                        "failed" if plan.failed else "not_cloned",
                        f"snippet `{plan.target}` not created: {plan.failed}"
                        if plan.failed
                        else f"in snippet `{plan.target}`, which "
                        + (
                            "is a PAN snippet"
                            if plan.action == "pan"
                            else "other folders use (allow_shared_snippet=False)"
                        ),
                    )
                )
                continue
            if obj.get("snippet") and plan is None:
                notes.append(f"from custom snippet `{obj['snippet']}`, cloned into the folder")
            if preflight is not None:
                if oid in preflight.skip:
                    report.results.append(
                        PushResult(
                            snap_key,
                            obj.get("name", "<unknown>"),
                            "ref_skipped",
                            preflight.skip[oid],
                        )
                    )
                    continue
                stripped = preflight.strip.get(oid)
                if stripped:
                    obj = dict(obj)
                    for fld, bad in stripped.items():
                        obj[fld] = [v for v in obj.get(fld) or [] if v not in bad]
                    notes.append(
                        "stripped "
                        + "; ".join(
                            f"{fld}: {', '.join(sorted(bad))}" for fld, bad in stripped.items()
                        )
                    )
            obj_folder = folder if folder != "customer" else target_folder
            o, psk_w = _sanitise(
                obj,
                target_folder=obj_folder,
                name_prefix="" if snap_key in UNRENAMED_KEYS else name_prefix,
                anonymise_ips=anonymise_ips,
                ip_map=ip_map,
                is_ike_gateway=is_ike_gateway,
                set_folder=not folder_kwarg and sdk_attr not in _FOLDERLESS_RESOURCES,
                rewrite=(lambda x: rewrite_references(snap_key, x, renames)) if renames else None,
                snippet=plan.target if plan is not None else "",
            )
            if psk_w:
                report.psk_warnings.append(psk_w)
            if network:
                scrubbed = _scrub_network_secrets(o, snap_key)
                if scrubbed:
                    report.secret_warnings.append(
                        f"{snap_key} `{o.get('name', '<unknown>')}`: {', '.join(scrubbed)}"
                    )
            if snap_key in _THREAT_RULE_PROFILES:
                _drop_empty_actions(o)
            if preflight is not None and oid in preflight.disable:
                o["disabled"] = True
                notes.append("created disabled — no forward-trust certificate")
            kwargs = dict(create_kwargs or {})
            if folder_kwarg:
                kwargs["folder"] = folder
            result = _push_one(
                client, sdk_attr, o, on_conflict, dry_run, snap_key, create_kwargs=kwargs
            )
            if notes:
                result.detail = "; ".join([result.detail, *notes] if result.detail else notes)
            report.results.append(result)

    for snap_key, sdk_attr, folder, opts in batches:
        into = bool(snippet_plans) and _snippet_capable(sdk_attr, folder, opts)
        _process_batch(snap_key, sdk_attr, folder, **opts, into_snippet=into)

    if duplicates:
        report.warnings.append(
            f"{len(duplicates)} network object(s) share a name with one from another source "
            f"folder ({', '.join(sorted(set(duplicates)))}); only the first of each name is "
            "pushed. The backup spans several firewall folders — back up the one firewall "
            "folder you want to restore instead."
        )
    return report
