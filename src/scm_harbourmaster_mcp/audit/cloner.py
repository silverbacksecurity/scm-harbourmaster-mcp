@dataclass
class PushResult:
    resource_type: str
    name: str
    # "created" | "skipped" | "overwritten" | "dry_run" | "failed" | "predefined"
    # | "ref_skipped" | "device_row" | "not_cloned"
    status: str
    detail: str = ""


@dataclass
class CloneReport:
    source_file: str
    target_folder: str
    target_tenant_id: str
    dry_run: bool
    results: list[PushResult] = field(default_factory=list)
    psk_warnings: list[str] = field(default_factory=list)
    # "<backup key> `<name>`: <field paths>" per network object whose secrets
    # were set to SECRET_PLACEHOLDER
    secret_warnings: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    preflight: PreflightResult | None = None

    # ── Counts ──────────────────────────────────────────────────────────
    @property
    def created(self) -> int:
        return sum(1 for r in self.results if r.status in ("created", "dry_run"))

    @property
    def skipped(self) -> int:
        return sum(1 for r in self.results if r.status == "skipped")

    @property
    def overwritten(self) -> int:
        return sum(1 for r in self.results if r.status == "overwritten")

    @property
    def failed(self) -> int:
        return sum(1 for r in self.results if r.status == "failed")

    @property
    def predefined(self) -> int:
        return sum(1 for r in self.results if r.status == "predefined")

    @property
    def ref_skipped(self) -> int:
        return sum(1 for r in self.results if r.status == "ref_skipped")

    @property
    def device_rows(self) -> int:
        return sum(1 for r in self.results if r.status == "device_row")

    @property
    def not_cloned(self) -> int:
        return sum(1 for r in self.results if r.status == "not_cloned")

    def to_markdown(self) -> str:
        lines: list[str] = []
        if self.preflight and self.preflight.blocked and not self.dry_run:
            mode = "BLOCKED BY PREFLIGHT"
        else:
            mode = "DRY RUN PREVIEW" if self.dry_run else "PUSH COMPLETE"
        lines.append(f"# SCM Config Clone — {mode}")
        lines.append(f"\n**Source:** `{self.source_file}`  ")
        lines.append(f"**Target folder:** `{self.target_folder}`  ")
        if self.target_tenant_id:
            lines.append(f"**Target tenant:** `{self.target_tenant_id}`  ")
        lines.append("")

        action = "Would create" if self.dry_run else "Created"
        lines.append("## Summary\n")
        lines.append("| Outcome | Count |")
        lines.append("|---|---|")
        lines.append(f"| {action} | {self.created} |")
        lines.append(f"| Skipped (conflict) | {self.skipped} |")
        if self.predefined:
            lines.append(f"| Skipped (PAN predefined) | {self.predefined} |")
        if self.ref_skipped:
            lines.append(f"| Skipped (preflight) | {self.ref_skipped} |")
        if self.device_rows:
            lines.append(f"| Skipped (set on a firewall, not a folder) | {self.device_rows} |")
        if self.not_cloned:
            lines.append(f"| Skipped (placeholder or duplicate name) | {self.not_cloned} |")
        if not self.dry_run:
            lines.append(f"| Overwritten | {self.overwritten} |")
        lines.append(f"| Failed | {self.failed} |")
        lines.append(f"| **Total** | **{len(self.results)}** |")

        lines += [f"\n⚠️ {w}" for w in self.warnings]

        if self.preflight:
            lines += self.preflight.to_markdown(self.dry_run)

        if self.psk_warnings:
            lines.append("\n## ⚠️ PSK Placeholders — Set Before Committing\n")
            lines.append("The following IKE gateways had their pre-shared keys replaced:")
            for w in self.psk_warnings:
                lines.append(f"- `{w}`")
            lines.append(
                "\nSet the real PSK via SCM UI or `scm_ike_gateway_update` before pushing commit."
            )

        if self.secret_warnings:
            lines.append("\n## ⚠️ Network Secret Placeholders — Set Before Committing\n")
            lines.append(
                f"These network objects had their secrets replaced with `{SECRET_PLACEHOLDER}` "
                "(backups hold them encrypted, which does not import):"
            )
            lines += [f"- {w}" for w in self.secret_warnings]
            lines.append("\nSet the real keys in the SCM UI before pushing the commit.")

        # Group results by type
        by_type: dict[str, list[PushResult]] = {}
        for r in self.results:
            by_type.setdefault(r.resource_type, []).append(r)

        if self.results:
            lines.append("\n## Detail\n")
            for rtype, items in by_type.items():
                lines.append(f"### {rtype} ({len(items)})\n")
                lines.append("| Name | Status | Detail |")
                lines.append("|---|---|---|")
                for r in items:
                    lines.append(f"| `{r.name}` | {r.status} | {r.detail} |")
                lines.append("")

        if self.failed > 0:
            lines.append("\n## ❌ Failures\n")
            for r in self.results:
                if r.status == "failed":
                    lines.append(f"- **{r.resource_type}** `{r.name}`: {r.detail}")

        return "\n".join(lines)


def _strip_system_fields(obj: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in obj.items() if k not in _SYSTEM_FIELDS}


def _snippet_types(data: dict[str, Any], client: Any) -> dict[str, str] | None:
    """Snippet name → SCM snippet type, from the backup or else the target.

    Backups written before snippet_types was recorded fall back to the
    target's snippet list: PAN snippets have the same names in every tenant.
    None when it is needed and neither source could be read.
    """
    # An empty map means the source snippet list failed to read, not that the
    # tenant has no snippets, so it falls back like a missing one.
    recorded = data.get("snippet_types")
    if isinstance(recorded, dict) and recorded:
        return {str(k): str(v) for k, v in recorded.items() if v}
    snippets = {
        str(o.get("snippet"))
        for objs in (data.get("resources") or {}).values()
        if isinstance(objs, list)
        for o in objs
        if isinstance(o, dict) and o.get("snippet")
    }
    if not any(not s.startswith("predefined") for s in snippets):
        return {}
    try:
        rows = client.snippet.list()
        return {str(r.name): str(r.type) for r in rows if getattr(r, "type", None)}
    except Exception as exc:
        logger.warning("clone_snippet_types_unavailable", error=str(exc)[:200])
        return None


